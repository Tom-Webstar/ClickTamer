package quartz

import "testing"

func TestResolve(t *testing.T) {
	cases := map[string]uint16{
		" A ": 0x00, "b": 0x0B, "c": 0x08, "d": 0x02, "e": 0x0E, "f": 0x03,
		"g": 0x05, "h": 0x04, "i": 0x22, "j": 0x26, "k": 0x28, "l": 0x25,
		"m": 0x2E, "n": 0x2D, "o": 0x1F, "p": 0x23, "q": 0x0C, "r": 0x0F,
		"s": 0x01, "t": 0x11, "u": 0x20, "v": 0x09, "w": 0x0D, "x": 0x07, "y": 0x10, "z": 0x06,
		"0": 0x1D, "1": 0x12, "2": 0x13, "3": 0x14, "4": 0x15,
		"5": 0x17, "6": 0x16, "7": 0x1A, "8": 0x1C, "9": 0x19,
		"F1": 0x7A, "f2": 0x78, "f3": 0x63, "f4": 0x76, "f5": 0x60, "f6": 0x61,
		"f7": 0x62, "f8": 0x64, "f9": 0x65, "f10": 0x6D, "f11": 0x67, "f12": 0x6F,
		"f01": 0x7A, "f+9": 0x65,
		"up": 0x7E, "down": 0x7D, "left": 0x7B, "right": 0x7C,
		"enter": 0x24, "space": 0x31, "tab": 0x30, "esc": 0x35, "escape": 0x35,
		"backspace": 0x33, "delete": 0x75, "insert": 0x72, "home": 0x73, "end": 0x77,
		"PAGEUP": 0x74, "pagedown": 0x79, "shift": 0x38, "ctrl": 0x3B, "alt": 0x3A, "capslock": 0x39,
		"-": 0x1B, "=": 0x18, ",": 0x2B, ".": 0x2F, "/": 0x2C, ";": 0x29,
		"'": 0x27, "[": 0x21, "]": 0x1E, "`": 0x32, "\\": 0x2A,
	}
	for token, want := range cases {
		got, err := Resolve(token)
		if err != nil || got != want {
			t.Errorf("Resolve(%q) = %#x, %v, want %#x", token, got, err, want)
		}
	}
}

func TestResolveRejectsUnknownTokens(t *testing.T) {
	for _, token := range []string{"", " ", "nope", "ab", "f0", "f13", "f123", "f1x", "é"} {
		if _, err := Resolve(token); err == nil {
			t.Errorf("Resolve(%q): want error", token)
		}
	}
}
